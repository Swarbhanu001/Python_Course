# 1. Convert an integer to a floating-point number
integer_value = 10
float_result = float(integer_value)
print(f"1. Integer {integer_value} converted to float: {float_result}")

# 2. Convert a floating-point number to an integer
float_value = 9.7
int_result = int(float_value)
print(f"2. Float {float_value} converted to int: {int_result}")

# 3. Convert an integer to a string
integer_value2 = 25
string_result = str(integer_value2)
print(f"3. Integer {integer_value2} converted to string: '{string_result}'")

# 4. Convert a string containing a number to an integer
string_value = "123"
int_from_string = int(string_value)
print(f"4. String '{string_value}' converted to int: {int_from_string}")

# 5. Convert an integer to a Boolean
integer_value3 = 0
bool_result = bool(integer_value3)
print(f"5. Integer {integer_value3} converted to bool: {bool_result}")